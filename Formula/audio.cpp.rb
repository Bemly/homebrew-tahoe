class AudioCpp < Formula
  desc "On-device speech and audio inference with the Bemly Metal fork"
  homepage "https://github.com/Bemly/audio.cpp"
  url "https://github.com/Bemly/audio.cpp/archive/0894a7cb9fd1efb3bce8dab7066b19bea33222b0.tar.gz"
  sha256 "25584ae2899c35f56346f6d0ddf208596c2c104873e76490ec42e498d5706f7f"
  version "2026.11.24-0894a7cb"
  license "Apache-2.0"
  compatibility_version 1

  bottle do
    root_url "https://ghcr.io/v2/bemly/tahoe"
    manifest_sha256 "1dfdb5d8a0fa1c7a86bc1b8773a499c7cda41ab9896faf386adc7ad01d40448d"
    sha256 cellar: :any_skip_relocation, tahoe: "617cdeab91fff18c4dda11880f4d076516f7f9b9256561fb5bd2d833b10aa210"
  end

  depends_on "bemly/tahoe/cmake" => :build
  depends_on "bemly/tahoe/ninja" => :build
  depends_on "bemly/tahoe/pkgconf" => :build
  depends_on arch: :x86_64
  depends_on macos: :tahoe

  deny_network_access!

  def install
    args = %W[
      -DCMAKE_BUILD_TYPE=Release
      -DBUILD_SHARED_LIBS=OFF
      -DENGINE_ENABLE_METAL=ON
      -DGGML_METAL_EMBED_LIBRARY=ON
      -DENGINE_ENABLE_NATIVE_CPU=OFF
      -DGGML_NATIVE=OFF
      -DENGINE_ENABLE_OPENMP=OFF
      -DAUDIOCPP_DEPLOYMENT_BUILD=ON
      -DAUDIOCPP_BUILD_NATIVE_MODEL_MANAGER=OFF
      -DAUDIOCPP_BUILD_SERVER_FRONTENDS=OFF
      -DAUDIOCPP_ZONOS3_TEXTNORM=OFF
      -DAUDIOCPP_MODEL_SET=custom
      -DAUDIOCPP_MODELS=sense_asr,parakeet_tdt,qwen3_asr
      -DAUDIOCPP_VERSION=#{version}
      -DGGML_SSE42=ON
      -DGGML_AVX=ON
      -DGGML_AVX2=ON
      -DGGML_FMA=ON
      -DGGML_F16C=ON
      -DGGML_BMI2=ON
      -DGGML_AVX_VNNI=OFF
      -DGGML_AVX512=OFF
    ]

    system "cmake", "-S", ".", "-B", "build", *args, *std_cmake_args,
           "-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0"
    system "cmake", "--build", "build", "--target", "audiocpp_cli", "audiocpp_server"

    %w[audiocpp_cli audiocpp_server].each do |binary|
      (libexec/"bin").install buildpath/"build/bin/#{binary}"
      bin.install_symlink libexec/"bin/#{binary}" => binary
    end

    models = libexec/"bin/assets/framework/models"
    models.mkpath
    models.install buildpath/"assets/framework/models/silero_vad"

    merged = buildpath/"build/ggml/src/ggml-metal/autogenerated/ggml-metal-embed.metal"
    if merged.file?
      air = libexec/"bin/ggml-metal.air"
      metallib = libexec/"bin/default.metallib"
      system "xcrun", "metal", "-O3", "-mmacosx-version-min=14.0", "-std=metal3.1",
             "-DGGML_METAL_EMBED_LIBRARY", "-DGGML_METAL_HAS_BF16",
             "-I", "external/ggml/src", "-I", "external/ggml/src/ggml-metal",
             "-c", merged, "-o", air
      system "xcrun", "metallib", air, "-o", metallib
      air.unlink
    end
  end

  test do
    assert_match(/usage/i, shell_output("#{bin}/audiocpp_cli --help 2>&1"))
  end
end
