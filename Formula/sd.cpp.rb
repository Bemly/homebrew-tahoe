class SdCpp < Formula
  desc "Stable Diffusion inference in C/C++ with the Bemly Metal fork"
  homepage "https://github.com/Bemly/stable-diffusion.cpp"
  url "https://github.com/Bemly/stable-diffusion.cpp/archive/629538202c950eb45d86bb8d7b254ed4972b6404.tar.gz"
  sha256 "010f6fb714ff8bf4f8ebb1ab8b2c09c401284be91b4407d180d984a595f6cb36"
  version "2026.11.24-62953820"
  license "MIT"
  compatibility_version 1

  depends_on "bemly/tahoe/cmake" => :build
  depends_on "bemly/tahoe/ninja" => :build
  depends_on "bemly/tahoe/pkgconf" => :build
  depends_on arch: :x86_64
  depends_on macos: :tahoe

  deny_network_access!

  def install
    args = %W[
      -DCMAKE_BUILD_TYPE=Release
      -DBUILD_SHARED_LIBS=OFF
      -DSD_BUILD_EXAMPLES=ON
      -DSD_METAL=ON
      -DSD_WEBP=OFF
      -DSD_WEBM=OFF
      -DSD_SERVER_BUILD_FRONTEND=OFF
      -DSD_USE_UPSTREAM_GGML=OFF
      -DGGML_METAL_EMBED_LIBRARY=ON
      -DGGML_NATIVE=OFF
      -DGGML_SSE42=ON
      -DGGML_AVX=ON
      -DGGML_AVX2=ON
      -DGGML_FMA=ON
      -DGGML_F16C=ON
      -DGGML_BMI2=ON
      -DGGML_AVX_VNNI=OFF
      -DGGML_AVX512=OFF
    ]

    system "cmake", "-S", ".", "-B", "build", *args, *std_cmake_args,
           "-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0"
    system "cmake", "--build", "build", "--target", "sd-cli", "sd-server"

    %w[sd-cli sd-server].each do |binary|
      (libexec/"bin").install buildpath/"build/bin/#{binary}"
      bin.install_symlink libexec/"bin/#{binary}" => binary
    end

    embed_dir = buildpath/"build/ggml/src/ggml-metal/autogenerated"
    metal_sources = Dir[embed_dir/"ggml-metal-embed-*.metal"].reject do |source|
      source.basename(".metal").to_s == "ggml-metal-embed-fa_tensor"
    end
    odie "sd.cpp Metal kernels were not generated" if metal_sources.empty?
    airs = metal_sources.map do |source|
      name = source.basename(".metal").to_s.delete_prefix("ggml-metal-embed-")
      air = libexec/"bin/#{name}.air"
      system "xcrun", "metal", "-O3", "-mmacosx-version-min=14.0", "-std=metal3.1",
             "-DGGML_METAL_EMBED_LIBRARY", "-DGGML_METAL_HAS_BF16",
             "-I", "ggml/src", "-I", "ggml/src/ggml-metal",
             "-c", source, "-o", air
      air
    end
    system "xcrun", "metallib", *airs, "-o", libexec/"bin/default.metallib"
    airs.each(&:unlink)
  end

  test do
    assert_match(/usage/i, shell_output("#{bin}/sd-cli --help 2>&1"))
  end
end
